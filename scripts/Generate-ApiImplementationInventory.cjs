// Generate the inventory from a running, isolated BHome.Api host's exported descriptors.
// Registration and source bindings are evidence of availability, not workflow acceptance.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const input = path.resolve(
  root,
  process.argv[2] || '.tmp/config-final-runtime/api-route-audit.json',
);
const audit = JSON.parse(fs.readFileSync(input, 'utf8'));
const date = process.argv[3];
if (!/^\d{4}-\d{2}-\d{2}$/.test(date || ''))
  throw new Error('Pass the verified generation date as YYYY-MM-DD.');
if (!/^[a-f0-9]{40}$/.test(audit.SourceCommit || ''))
  throw new Error('The runtime export must record BHOME_API_INVENTORY_COMMIT.');
if (!audit.SchemaVerified || audit.TableCount !== 24)
  throw new Error('A verified Compact24 runtime export is required.');
const endpoints = [...audit.Endpoints].sort(
  (a, b) =>
    a.Controller.localeCompare(b.Controller) ||
    a.Route.localeCompare(b.Route) ||
    a.Method.localeCompare(b.Method),
);
if (new Set(endpoints.map((e) => `${e.Method} ${e.Route}`)).size !== endpoints.length)
  throw new Error('Duplicate method-route descriptors.');
if (endpoints.some((e) => !e.Anonymous && e.AnonymousStatus !== 401))
  throw new Error('A protected route failed the anonymous authentication probe.');
const protectedCount = endpoints.filter((e) => !e.Anonymous).length;
const statuses = audit.OwnerGetProbes.reduce((counts, probe) => {
  counts[probe.Status] = (counts[probe.Status] || 0) + 1;
  return counts;
}, {});
const bindings = {
  SharedConfiguration:
    '[Shared libraries](../../src/owner-web/src/features/configuration/pages/ApiConfigurationLibraryPage.tsx)',
  SharedApplication:
    '[Apply and usage](../../src/owner-web/src/features/configuration/pages/SharedTemplateDetails.tsx)',
  LocationConfigurationCopy:
    '[Location copy](../../src/owner-web/src/features/configuration/ApiConfigurationCopy.tsx)',
  AssetInventory:
    '[Local inventory](../../src/owner-web/src/features/property/LocalAssetSetup.tsx)',
  UtilityWorkspace:
    '[Utility workspace](../../src/owner-web/src/features/property/UtilityWorkspace.tsx)',
  UtilitySourceReadings:
    '[Utility operations](../../src/owner-web/src/features/property/UtilityWorkspaceOperations.tsx)',
  OperatingPolicies:
    '[Operating policies](../../src/owner-web/src/features/property/OperatingPoliciesPanel.tsx)',
  SetupEvidence:
    '[Private evidence](../../src/owner-web/src/features/property/SetupEvidenceField.tsx)',
};
const lines = [
  '# Runtime API route inventory',
  '',
  `Generated: **${date}**, runtime export UTC: **${audit.GeneratedAtUtc}**.`,
  '',
  `Source commit: \`${audit.SourceCommit}\`. Branch: \`member/QHuy\`.`,
  '',
  `**${endpoints.length} registered controller method-route pairs**: ${protectedCount} protected and ${endpoints.length - protectedCount} anonymous.`,
  `**${audit.SwaggerMethodRoutePairs} OpenAPI operations / ${audit.SwaggerPathCount} path keys**. Two health endpoints are counted separately.`,
  '',
  'Counting method: IActionDescriptorCollectionProvider from the instantiated BHome.Api host, filtered to the product controller assembly, expanded by HTTP method and attribute route. Generic resource routes count once per method/path pattern, not once for every allowed resource value.',
  '',
  "OpenAPI is generated by that host's registered ISwaggerProvider. Test-assembly probe paths are excluded. The Development mobile certificate endpoint is registered but deliberately hidden from OpenAPI. Swagger middleware itself is enabled only in Development; the test host uses Testing and synthetic configuration.",
  '',
  `Persistence: \`${audit.SchemaVersion}\`; **${audit.TableCount} physical public tables**, schema verifier passed on disposable PostgreSQL 16. No working database writes or new migration.`,
  '',
  `All ${protectedCount} protected descriptors returned 401 without authentication. Owner GET probe results: \`${JSON.stringify(statuses)}\`.`,
  '',
  'GET probes include missing IDs, invalid resource values and omitted queries. A registration or non-5xx probe does not establish a successful business workflow. See [validation](../development/CONFIGURATION_VALIDATION_2026-11-09.md) for executed workflow tests and unresolved baseline failures.',
  '',
  'The client column links the configuration UI reviewed in this task. It is not an exhaustive consumer/dependency inventory. Other modules require their own client verification; no absence or completion is inferred.',
  '',
];
for (const controller of [...new Set(endpoints.map((e) => e.Controller))]) {
  lines.push(
    `## ${controller}`,
    '',
    '| Method and route | Action / parameters | Entry authorization | Configuration client evidence |',
    '| --- | --- | --- | --- |',
  );
  for (const endpoint of endpoints.filter((e) => e.Controller === controller)) {
    const authorization = endpoint.Anonymous
      ? 'Anonymous'
      : endpoint.Authorization.map((a) => a.Policy || a.Roles || 'Authenticated').join(' + ');
    const parameters =
      endpoint.Parameters.filter((p) => p.Type !== 'CancellationToken')
        .map((p) => `${p.Name}: ${p.Type}${p.Source ? ' (' + p.Source + ')' : ''}`)
        .join('; ') || 'No parameters';
    const clean = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
    lines.push(
      `| \`${endpoint.Method} ${endpoint.Route}\` | ${clean(endpoint.Action)}: ${clean(parameters)} | ${clean(authorization)} | ${bindings[controller] || 'Not assessed in this configuration inventory'} |`,
    );
  }
  lines.push('');
}
lines.push(
  '## Health endpoints',
  '',
  '| Route | Meaning |',
  '| --- | --- |',
  '| `GET /health/live` | Anonymous host liveness |',
  '| `GET /health/ready` | Anonymous structural readiness; no secrets in response |',
  '',
  '## Reproduction',
  '',
  'Export through Compact24ApiAuditTests using BHOME_COMPACT24_EVIDENCE_DIRECTORY and BHOME_API_INVENTORY_COMMIT, then run this generator with the manifest path and verified date. Use the disposable runner described in [API status](API_IMPLEMENTATION_STATUS.md#reproduction).',
  '',
);
fs.writeFileSync(path.join(root, 'docs/api/API_RUNTIME_ROUTES.md'), lines.join('\n'));
console.log(
  `Wrote ${endpoints.length} registered pairs; ${audit.SwaggerMethodRoutePairs} OpenAPI operations; ${audit.SwaggerPathCount} path keys.`,
);
